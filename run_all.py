def process_one(dev_type, pdf_path):
    """Process a single device passport and generate functional diagram."""
    log.info(f"\n{'='*60}")
    log.info(f"Processing {dev_type}: {pdf_path}")
    log.info(f"{'='*60}")

    if not os.path.exists(pdf_path):
        log.error(f"  FILE NOT FOUND: {pdf_path}")
        return None

    # Build fresh model from seed only
    model = SystemModel()
    spec = SEEDS.get(dev_type, {})
    model.title = spec.get('title', dev_type)
    model.subtitle = os.path.splitext(os.path.basename(pdf_path))[0]
    model = apply_seed(model, spec)

    log.info(f"  Total: {len(model.components)} components, "
             f"{len(model.relations)} relations, {len(model.groups)} groups")
    log.info(f"  Modes: {list(spec.get('modes', {}).get('flow', {}).keys())}")

    # Build combined functional diagram
    stem = os.path.join(OUTPUT_DIR, f'{dev_type}_diagram')
    png, pdf = build_functional_diagram(model, spec, stem)
    if png:
        log.info(f"  => {png}")
        log.info(f"  => {pdf}")
    else:
        log.warning(f"  Render failed for {dev_type}")

    return model


