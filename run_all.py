# ── Helper: build curtain connections for BKU variants ──
def _bku_curtain_entries(count, contactor_prefix='КМ', start_km=1):
    """Generate component tuples, connections, and control flow for N curtains.

    Each curtain gets 3 contactors (e.g. КМ1-КМ3 for curtain 1).
    Returns (components_extra, connections_extra, flow_entries) where
    each is a list to be merged into the seed.
    """
    comps = []
    conns = []
    flow_auto = []  # Автоматический mode flow
    flow_manual = []  # Ручной mode flow

    for i in range(1, count + 1):
        km_start = start_km + (i - 1) * 3
        km_names = [f'{contactor_prefix}{km_start + j}' for j in range(3)]

        # Component entries
        curtain_label = f'Завеса {i}'
        for km in km_names:
            pass
        # contactors are added in the main seed dict

        # Connections: each curtain's contactors -> curtain
        for km in km_names:
            conns.append((f'Контактор {km}', f'Завеса {i}', 'подключен'))

        # Control flow for this curtain
        km_ids_str = ','.join(km_names)
        flow_auto.append((f'Контактор {km_names[0]}', f'Завеса {i}', 'ПУСК', 'power'))
        flow_manual.append((f'Контактор {km_names[0]}', f'Завеса {i}', 'ПУСК', 'power'))

    return comps, conns, flow_auto, flow_manual


