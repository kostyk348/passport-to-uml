        ('Клеммная колодка X5', _f('Клеммная колодка X5', 'electrical', 'Узел терморегулирования')),
        ('Клеммная колодка X7', _f('Клеммная колодка X7', 'electrical', 'Концевой выключатель + ТЗЗ')),
