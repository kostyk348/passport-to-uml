# APPLY SEED TO MODEL
# ──────────────────────────────────────────────────────────────────────

def apply_seed(model, seed):
    """Apply seed components, connections, and groups to model."""
    for cid, (name, cat, desc) in seed.get('components', {}).items():
        real_id = _name_to_id(name)
        comp = Component(real_id, name, cat, desc)
        if real_id not in model.components:
            model.add_component(comp)

    for from_name, to_name, label in seed.get('connections', []):
        if from_name and to_name:
            model.get_or_create(from_name)
            model.get_or_create(to_name)
            model.relate(from_name, to_name, label)

    for gname, comps in seed.get('groups', {}).items():
        model.add_group(gname, comps)

    curtain_count = seed.get('curtains', 0)
    for i in range(1, curtain_count + 1):
        name = f'Завеса {i}'
        if not model.has_component(name):
            model.get_or_create(name, 'airflow')

    return model


