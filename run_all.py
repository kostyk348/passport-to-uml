    # Build control flow for this curtain count
    # Автоматический: концевой выключатель → БКУ → КМ1 → Завеса1, КМ4 → Завеса2, ...
    flow_auto = []
    flow_manual = []
    for i in range(1, curtain_count + 1):
        first_km = f'Контактор КМ{km_start + (i-1)*3}'
