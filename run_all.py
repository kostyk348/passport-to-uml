        ('Реле К1', _f('Реле К1', 'electrical', '')),
        ('Реле К2', _f('Реле К2', 'electrical', '')),
        ('Узел терморегулирования', _f('Узел терморегулирования', 'hydronic', 'Насос + клапан')),
        ('Циркуляционный насос', _f('Циркуляционный насос', 'hydronic', '')),
        ('Электропривод клапана', _f('Электропривод клапана', 'hydronic', 'Трехходовой')),
        ('Концевой выключатель', _f('Концевой выключатель', 'control', '')),
        ('Внешний термостат', _f('Внешний термостат', 'control', '')),
